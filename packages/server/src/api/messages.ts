// Inserting a message anywhere in a fork's history (spec/MESSAGE-INSERT.md §4, §5; owner
// decision DESIGN §3.1, 2026-10-30). The RPC dispatches through the registered command
// `message.insert`, so a plugin can replace it and an agent inserts messages the same way.
import { CurrentUser, type AppApi } from "@rp/shared/api.ts"
import { PathEntry } from "@rp/shared/chat.ts"
import { GenerationUnavailable } from "@rp/shared/chatApi.ts"
import { StaleWrite } from "@rp/shared/errors.ts"
import { InsertedMessage, InsertMessageInput, InsertRefused } from "@rp/shared/messagesApi.ts"
import { Effect, Option } from "effect"
import { ChatHub } from "../chat/ChatHub.ts"
import { Generations } from "../chat/Generations.ts"
import { Generator } from "../chat/Generator.ts"
import { Commands, makeCommand, runCommand } from "../commands.ts"
import { Reader, Writer } from "../db/Database.ts"
import { internal } from "./internal.ts"

export const makeMessageHandlers = Effect.gen(function* () {
  const reader = yield* Reader
  const writer = yield* Writer
  const hub = yield* ChatHub
  const generations = yield* Generations
  const generator = yield* Generator
  const commands = yield* Commands

  const insert = ({ chatId, forkId, anchor, expectedRowVersion, body }: InsertMessageInput) =>
    Effect.gen(function* () {
      const user = yield* CurrentUser
      if (body._tag === "Generate" && Option.isNone(generator))
        return yield* new GenerationUnavailable({ message: "This server has nothing to generate with." })
      const result = yield* writer.InsertMessage({
        userId: user.id,
        chatId,
        forkId,
        anchorSlotId: anchor,
        expectedRowVersion,
        body
      })
      // Generated at the insertion point as a swipe is: the context is the fork's display path
      // up to the anchor (the target's place), never what follows it (DESIGN §3.1 [D]). Once the
      // version is written, its generation starts even if the caller has gone.
      if (body._tag === "Generate")
        yield* generations.start({
          userId: user.id,
          chatId,
          slotId: result.slotId,
          versionId: result.version.id,
          forkId: result.forkId
        })
      // The fork's tabs place the new slot by its position; other forks' tabs don't show it.
      // Inserting changes none of the anchor's choices, so the anchor has no event of its own.
      const { entry } = yield* reader.GetSlot({ userId: user.id, slotId: result.slotId, forkId: result.forkId })
      const placed = new PathEntry({ ...entry, position: result.position })
      hub.publish(chatId, { _tag: "Slot", entry: placed })
      hub.publish(chatId, { _tag: "Chat", chat: result.chat })
      // A summary covering the anchor is stale in the fork now (spec §3.4).
      hub.publish(chatId, { _tag: "Lcm" })
      return new InsertedMessage({ entry: placed, chat: result.chat })
    }).pipe(Effect.uninterruptible, internal("InsertMessage"))

  yield* commands.register(
    makeCommand({
      id: "message.insert",
      description:
        "Insert a message anywhere in a fork's history: written as a speaker, generated by the model at that point, or a copy of the message above.",
      input: InsertMessageInput,
      output: InsertedMessage,
      execute: insert
    })
  )

  return {
    InsertMessage: (params) =>
      runCommand(commands, "message.insert", params, InsertedMessage, [
        StaleWrite,
        InsertRefused,
        GenerationUnavailable
      ])
  } satisfies Partial<Parameters<typeof AppApi.of>[0]>
})
