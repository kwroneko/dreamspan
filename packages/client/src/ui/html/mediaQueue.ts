/** CSS generated by the scoper: skip whole strings/comments, replacing only URL tokens.
 * Inert content strings and selector text must never become prefetch requests. */
export const mapCssMedia = (css: string, replace: (url: string) => string) =>
  css.replace(
    /\/\*[\s\S]*?\*\/|"(?:[^"\\]|\\[\s\S])*"|'(?:[^'\\]|\\[\s\S])*'|url\("(\/media\/external\?[^"\\]*)"\)/g,
    (whole, url: string | undefined) => (url === undefined ? whole : `url("${replace(url)}")`)
  )

/** Only complete app media addresses, never an address embedded in a data URI or prose. */
export const mapMediaAttribute = (value: string, srcset: boolean, replace: (url: string) => string) => {
  if (!srcset) return /^\/media\/external\?[^\s"'<>]+$/.test(value) ? replace(value) : value
  const candidates = value
    .split(",")
    .map((entry) => /^(\/media\/external\?[^\s"'<>,]+)(\s+(?:\d+w|[\d.]+x))?$/.exec(entry.trim()))
  if (!candidates.length || candidates.some((candidate) => candidate === null)) return value
  return candidates.map((candidate) => `${replace(candidate![1]!)}${candidate![2] ?? ""}`).join(", ")
}
