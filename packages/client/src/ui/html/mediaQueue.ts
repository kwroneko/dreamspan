/** Live views share four downloads. A 429 waits outside the active slots and retries;
 * nothing persists after the last view releases it (including consent revocation). */
export const makeMediaQueue = (
  fetchMedia: typeof fetch = (...args) => fetch(...args),
  blobs = { create: (blob: Blob) => URL.createObjectURL(blob), revoke: (url: string) => URL.revokeObjectURL(url) }
) => {
  interface Entry {
    readonly url: string
    readonly controller: AbortController
    readonly listeners: Set<() => void>
    result: string | null
    timer?: ReturnType<typeof setTimeout>
  }
  const entries = new Map<string, Entry>()
  const waiting: Entry[] = []
  let active = 0
  const pump = () => {
    while (active < 4 && waiting.length) {
      const entry = waiting.shift()!
      if (entry.controller.signal.aborted) continue
      active++
      void (async () => {
        try {
          const response = await fetchMedia(entry.url, {
            signal: entry.controller.signal,
            credentials: "same-origin",
            cache: "no-store"
          })
          if (response.status === 429) {
            const retry = response.headers.get("retry-after") ?? "1"
            const seconds = /^\d+(?:\.\d+)?$/.test(retry) ? Number(retry) : (Date.parse(retry) - Date.now()) / 1000
            await response.body?.cancel()
            if (!entry.controller.signal.aborted)
              entry.timer = setTimeout(
                () => {
                  waiting.push(entry)
                  pump()
                },
                Math.max(1000, Number.isFinite(seconds) ? seconds * 1000 : 1000)
              )
          } else if (response.ok) {
            const blob = await response.blob()
            if (!entry.controller.signal.aborted) {
              entry.result = blobs.create(blob)
              for (const listener of entry.listeners) listener()
            }
          } else await response.body?.cancel()
        } catch {
          /* Unmounts and consent changes abort pending downloads. */
        } finally {
          active--
          pump()
        }
      })()
    }
  }
  return {
    read: (url: string) => entries.get(url)?.result ?? null,
    retain(url: string, listener: () => void) {
      let entry = entries.get(url)
      if (!entry) {
        entry = { url, controller: new AbortController(), listeners: new Set(), result: null }
        entries.set(url, entry)
        waiting.push(entry)
      }
      entry.listeners.add(listener)
      pump()
      return () => {
        entry.listeners.delete(listener)
        if (entry.listeners.size) return
        entry.controller.abort()
        clearTimeout(entry.timer)
        if (entry.result) blobs.revoke(entry.result)
        entries.delete(url)
        const at = waiting.indexOf(entry)
        if (at >= 0) waiting.splice(at, 1)
      }
    }
  }
}

