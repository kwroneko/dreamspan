// Writes src/ui/html/purifyLists.ts: DOMPurify's default allow-lists (the version ST pins),
// as the tag and property names our HTML parser gives them, for the message sanitizer
// (src/ui/html/schema.ts, spec/HTML-MESSAGES.md §3.2). `node packages/client/scripts/htmlSchema.ts`
// regenerates it; test/htmlSanitize.test.ts fails while the file differs from what this makes.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import { html as htmlInfo } from "property-information"
import rehypeRaw from "rehype-raw"

const require = createRequire(import.meta.url)
export const OUTPUT = fileURLToPath(new URL("../src/ui/html/purifyLists.ts", import.meta.url))

interface Node {
  type: string
  tagName?: string
  properties?: Record<string, unknown>
  children?: Node[]
}

/** One `const name = freeze([...])` (or `addToSet({}, [...])`) list from DOMPurify's build. */
function list(source: string, name: string): string[] {
  const escaped = name.replaceAll("$", "\\$")
  const match = new RegExp(`const ${escaped} = (?:freeze\\(|addToSet\\(\\{\\}, )\\[([^\\]]*)\\]`).exec(source)
  if (!match) throw new Error(`DOMPurify's ${name} list wasn't found`)
  // DOMPurify compares lowercased names (its default transformCaseFunc).
  return [...match[1]!.matchAll(/'([^']*)'/g)].map((item) => item[1]!.toLowerCase())
}

/** What the parser makes of `markup`, as rehype-raw parses message HTML. */
function parse(markup: string): Node {
  return rehypeRaw()({ type: "root", children: [{ type: "raw", value: markup }] } as never, undefined as never) as Node
}
function* elements(node: Node): Generator<Node> {
  for (const child of node.children ?? []) {
    if (child.type === "element") yield child
    yield* elements(child)
  }
}

/** The tag name the parser gives a lowercased name in its own namespace (SVG's camelCase). */
function tagName(name: string, wrap: (inner: string) => string) {
  const found = [...elements(parse(wrap(`<${name}></${name}>`)))].at(-1)
  return found?.tagName?.toLowerCase() === name ? found.tagName : name
}
/** The hast property names an attribute gets on HTML, SVG and MathML elements. */
function properties(attribute: string): string[] {
  const names = new Set<string>()
  for (const markup of [
    `<div ${attribute}="x"></div>`,
    `<svg ${attribute}="x"></svg>`,
    `<math ${attribute}="x"></math>`
  ])
    for (const element of elements(parse(markup)))
      for (const key of Object.keys(element.properties ?? {})) names.add(key)
  return [...names]
}

export function generate(): string {
  const path = require.resolve("dompurify/dist/purify.js")
  const source = readFileSync(path, "utf8")
  const version = /DOMPurify\.version = '([^']+)'/.exec(source)?.[1]
  if (!version) throw new Error("DOMPurify's version wasn't found")
  const svgWrap = (inner: string) => `<svg>${inner}</svg>`
  const mathWrap = (inner: string) => `<math>${inner}</math>`
  const tags = new Set<string>()
  for (const name of list(source, "html$1")) tags.add(name)
  for (const name of [...list(source, "svg$1"), ...list(source, "svgFilters")])
    tags.add(name === "svg" ? name : tagName(name, svgWrap))
  for (const name of list(source, "mathMl$1")) tags.add(tagName(name, mathWrap))
  const attributes = new Set<string>()
  for (const name of [
    ...list(source, "html"),
    ...list(source, "svg"),
    ...list(source, "mathMl"),
    ...list(source, "xml")
  ])
    for (const property of properties(name)) attributes.add(property)
  // DOMPurify allows every `aria-*` attribute (ALLOW_ARIA_ATTR); the sanitizer lists them.
  for (const property of Object.keys(htmlInfo.property)) if (/^aria[A-Z]/.test(property)) attributes.add(property)
  const strip = list(source, "DEFAULT_FORBID_CONTENTS").map((name) =>
    ["foreignobject", "annotation-xml"].includes(name)
      ? tagName(name, name === "foreignobject" ? svgWrap : mathWrap)
      : name
  )
  const format = (values: Iterable<string>) => JSON.stringify([...values].sort(), null, 2)
  return [
    `// Generated by packages/client/scripts/htmlSchema.ts from DOMPurify ${version}'s default lists. Don't edit:`,
    "// run the script again. Names are as our HTML parser gives them (SVG's camelCase, hast properties).",
    `export const PURIFY_VERSION = "${version}"`,
    "/** Elements DOMPurify keeps: HTML, SVG, SVG filters and MathML. */",
    `export const TAG_NAMES: ReadonlyArray<string> = ${format(tags)}`,
    "/** Attributes DOMPurify keeps on any of them, as hast property names, `aria-*` included. */",
    `export const ATTRIBUTES: ReadonlyArray<string> = ${format(attributes)}`,
    "/** Elements whose content DOMPurify drops with them (FORBID_CONTENTS), when they aren't kept. */",
    `export const FORBID_CONTENTS: ReadonlyArray<string> = ${format(strip)}`,
    ""
  ].join("\n")
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeFileSync(OUTPUT, generate())
